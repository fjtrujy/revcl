char *AlignString(const char *text, int alignment)
{
    static char formatted[256];
    strcpy(formatted, text);
    char *space = strchr(formatted, ' ');
    if (space) {
        int offset = space - formatted;
        if (offset < alignment) {
            int padding = alignment - offset;
            for (int i = 0; i < padding; ++i)
                space[i] = ' ';
            space[padding] = 0;
            strcat(space, text + offset);
        }
    }
    return formatted;
}

#include <cstring>
#include <vector>

class Instruction {
public:
    const char *ToString();
};

class InstructionList {
public:
    std::vector<Instruction *> instructions_;
};

extern int constantsTabStop;

void AsmOutput_TabConstants(InstructionList &list)
{
    int count = list.instructions_.size();
    for (int i = 0; i < count; ++i) {
        const char *text = list.instructions_[i]->ToString();
        const char *delimiter = std::strstr(text, ".assign");
        if (!delimiter)
            delimiter = std::strstr(text, ".equ");
        if (delimiter) {
            int width = delimiter - text;
            if (width > constantsTabStop)
                constantsTabStop = width;
        }
    }
}
