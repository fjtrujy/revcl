#!/usr/bin/env python3
"""Investigate the one remaining exception-landing NOP in Enter (2026-10-15).

The original 185-byte SymbolTable::Enter has its first 0x30 bytes and
bucket stores reproduced by the true MLHashTable::Node source when aligned
to an 8-byte allocation branch. Under those source/flags GCC emits 186 bytes
solely because it aligns the trailing C++ EH landing pad to 8 at +0xa8
rather than original +0xa7. Test a bounded set of basic-block/scheduling
options that could change an EH block's perceived jump-target status.
Never add asm, fabricated labels, section padding or raw byte changes.
"""
from pathlib import Path
import importlib.util
import json
import re
import subprocess

ROOT=Path(__file__).resolve().parents[2]
VUC=ROOT/"vuc"
OUT=Path("/tmp/vuc-binutils215/enter-exception-landing-oct15m")
OUT.mkdir(parents=True, exist_ok=True)
spec=importlib.util.spec_from_file_location("match",VUC/"scripts/match_probe.py")
match=importlib.util.module_from_spec(spec)
spec.loader.exec_module(match)

# Prior verified scratch source: genuine source-unit ordering and actual
# nested hash node constructor. It is regenerated by the prior repo driver.
SRC=Path("/tmp/vuc-binutils215/symboltable-nested-node-oct15k/SymbolTableWithNestedNode.cpp")
if not SRC.exists():
    raise SystemExit("Run evaluate_symboltable_real_nested_node_oct15k.py first")
base=["-O2","-frename-registers","-falign-jumps=8","-falign-loops=1","-falign-labels=1"]
choices={
  "baseline":[],
  "no-reorder-blocks":["-fno-reorder-blocks"],
  "no-guess-branch-probability":["-fno-guess-branch-probability"],
  "no-crossjumping":["-fno-crossjumping"],
  "no-schedule-insns2":["-fno-schedule-insns2"],
  "no-schedule-insns":["-fno-schedule-insns"],
}
sym="_ZN11SymbolTable5EnterERK12MLGameStringP16SymbolTableEntry"
configs={"enter":"symboltable_enter_oct13_probe.json","scope":"scope_vector_insert_partial_oct15i.json",
         "find":"symboltable_find_probe.json","begin":"symbol_begin_scope_probe.json"}
results=[]
for compiler in ("jan25","dec06"):
  for label,flags in choices.items():
    obj=OUT/(compiler+"-"+label+".o")
    p=subprocess.run(["/tmp/vuc-binutils215/g++-"+compiler+"-as215",*base,*flags,
                      "-c",str(SRC),"-o",str(obj)],capture_output=True,text=True)
    row={"snapshot":compiler,"control":label}
    if p.returncode:
      row["error"]=p.stderr[-250:]
      results.append(row)
      print(row,flush=True)
      continue
    nm=subprocess.check_output(["nm","-S","--defined-only",str(obj)],text=True)
    found=next((line.split() for line in nm.splitlines() if line.endswith(" "+sym)),None)
    row["size"]=int(found[1],16) if found else None
    # Only invoke strict target-normalized original-byte comparison with its
    # authenticated correct function size. Do not promote wrong-size overlap.
    if row["size"]==185:
      for kind,config in configs.items():
        try:
          score=match.run(obj,VUC/"config"/config)
          row[kind]={"exact_bytes":score["exact_bytes"],"length":score["length"],
                     "relocations":score["relocations"],
                     "different_offsets":score["different_offsets"][:25]}
        except ValueError as exc:
          row[kind]={"error":str(exc)}
    results.append(row)
    print(row,flush=True)
(OUT/"results.json").write_text(json.dumps(results,indent=2)+"\n")
