#!/usr/bin/env python3
"""Genuine GCC3.3 STL iterator-copy original 149-byte target: EH specs & passes.

The period libstdc++ template + original 513-bucket Scope representation
naturally compiles 147-byte code with all six original relocations at
-falign-labels=4. Probe C++03 destructor/clear exception specifications and
historical compiler passes for the two missing compiler-generated bytes.
No dummy call, fabricated layout or source padding.
"""
from pathlib import Path
import itertools,json,subprocess,importlib.util,collections
R=Path(__file__).resolve().parents[2];s=importlib.util.spec_from_file_location('m',R/'vuc/scripts/match_probe.py');m=importlib.util.module_from_spec(s);s.loader.exec_module(m)
cfg=json.loads((R/'vuc/config/scope_iterator_copy_oct12_probe.json').read_text())
cppbase=(R/'vuc/probes/scope_iterator_clear_throw_oct14.cpp').read_text()
cppbase=cppbase.replace('#include "../src/MLHashFunGameString.h"','#include "'+str(R/'vuc/src/MLHashFunGameString.h')+'"')
hdrbase=(R/'vuc/src/ScopeCopyTable.h').read_text()
assert '~MLHashTable() { clear(); }' in hdrbase and 'void clear() throw();' in hdrbase
headers={
 'original':hdrbase,
 'dtor-noexcept':hdrbase.replace('~MLHashTable() { clear(); }','~MLHashTable() throw() { clear(); }'),
 'dtor-attribute':hdrbase.replace('~MLHashTable() { clear(); }','~MLHashTable() __attribute__((nothrow)) { clear(); }'),
 'clear-ordinary':hdrbase.replace('void clear() throw();','void clear();'),
 'clear-attribute':hdrbase.replace('void clear() throw();','void clear() __attribute__((nothrow));'),
 'dtor-outside':hdrbase.replace('~MLHashTable() { clear(); }','~MLHashTable();').replace('#endif','template <class Key,class Value,class Hasher,int Buckets>\nMLHashTable<Key,Value,Hasher,Buckets>::~MLHashTable() { clear(); }\n#endif'),
}
flags={
 'baseline':['-O2','-frename-registers','-falign-jumps=4','-falign-labels=4'],
 'plain':['-O2','-falign-jumps=4','-falign-labels=4'],
 'j1':['-O2','-frename-registers','-falign-jumps=1','-falign-labels=4'],
 'j8':['-O2','-frename-registers','-falign-jumps=8','-falign-labels=4'],
 'j16':['-O2','-frename-registers','-falign-jumps=16','-falign-labels=4'],
 'no-cross':['-O2','-frename-registers','-falign-jumps=4','-falign-labels=4','-fno-crossjumping'],
 'no-reorder':['-O2','-frename-registers','-falign-jumps=4','-falign-labels=4','-fno-reorder-blocks'],
 'no-sched2':['-O2','-frename-registers','-falign-jumps=4','-falign-labels=4','-fno-schedule-insns2'],
 'no-regmove':['-O2','-frename-registers','-falign-jumps=4','-falign-labels=4','-fno-regmove'],
 'no-gcse':['-O2','-frename-registers','-falign-jumps=4','-falign-labels=4','-fno-gcse'],
 'no-thread':['-O2','-frename-registers','-falign-jumps=4','-falign-labels=4','-fno-thread-jumps'],
 'no-guess':['-O2','-frename-registers','-falign-jumps=4','-falign-labels=4','-fno-guess-branch-probability'],
 'no-cprop':['-O2','-frename-registers','-falign-jumps=4','-falign-labels=4','-fno-cprop-registers'],
 'labels3':['-O2','-frename-registers','-falign-jumps=4','-falign-labels=3'],
 'labels5':['-O2','-frename-registers','-falign-jumps=4','-falign-labels=5'],
 'cost1':['-O2','-frename-registers','-falign-jumps=4','-falign-labels=4','-mbranch-cost=1'],
}
T=Path('/tmp/vuc-binutils215/scope-iterator-spec-align-oct15e');T.mkdir(parents=True,exist_ok=True)
raw,elf=m.decomp.load();sec=next(x for x in elf['sections'] if x['name']=='.text');a=int(cfg['address'],0);ref=raw[sec['offset']+a-sec['address']:sec['offset']+a-sec['address']+149]
rows=[];sizes=collections.Counter();best=None
for (hn,header),(fn,opts) in itertools.product(headers.items(),flags.items()):
 tag=hn+'-'+fn;inc=T/(tag+'.h');cpp=T/(tag+'.cpp');obj=T/(tag+'.o')
 inc.write_text(header)
 cpp.write_text(cppbase.replace('#include "../src/ScopeCopyTable.h"','#include "'+str(inc)+'"'))
 p=subprocess.run(['/tmp/vuc-binutils215/g++-jan25-as215',*opts,'-c',str(cpp),'-o',str(obj)],capture_output=True,text=True)
 if p.returncode:rows.append(dict(tag=tag,error=p.stderr[-150:]));continue
 try:b,rel=m.prepare_named_function(obj.read_bytes(),cfg['function'],cfg['relocations'],a)
 except ValueError as e:rows.append(dict(tag=tag,error=str(e)[:170]));continue
 match=sum(x==y for x,y in zip(ref,b));px=next((i for i,(x,y) in enumerate(zip(ref,b)) if x!=y),min(len(ref),len(b)))
 row=dict(tag=tag,length=len(b),match=match,prefix=px,relocations=rel);rows.append(row);sizes[len(b)]+=1
 if len(b)==149 and rel==6 and (best is None or (match,px)>(best['match'],best['prefix'])):
  best=row;(T/'best.cpp').write_text(cpp.read_text());(T/'best.h').write_text(header);(T/'best.o').write_bytes(obj.read_bytes());(T/'best.flags').write_text(' '.join(opts)+'\n')
  print('STRICT-ORIGINAL-LENGTH',json.dumps(row),flush=True)
  if match==149:print('EXACT',json.dumps(row),flush=True);break
(T/'results.json').write_text(json.dumps(rows,indent=2)+'\n')
print(json.dumps(dict(attempted=len(rows),sizes=dict(sizes),best=best,top=sorted((r for r in rows if 'match' in r),key=lambda r:(r['match'],r['prefix']),reverse=True)[:15]),indent=2))
